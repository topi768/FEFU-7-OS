#include <iostream>
#include "process.h"

using namespace std;

// argc - количество слов командной строки, включая имя самой утилиты
// argv - массив этих слов: argv[0] - имя утилиты, argv[1] - переданный путь
// Например: process_test.exe .\child.exe
int main(int argc, char* argv[])
{
#ifdef _WIN32
    // Строки сохранены в UTF-8. Выбираем эту кодировку для вывода в консоль Windows
    SetConsoleOutputCP(CP_UTF8);
#endif

    // Требуем один аргумент: путь к программе, которую нужно запустить
    if (argc != 2)
    {
        cout << "Использование: process_test <путь_к_программе>" << endl;
        return 1;
    }

    // Здесь будет дескриптор Windows или PID в POSIX
    Process child;

    // argv[1] задаёт, какую программу запускать
    // При успехе функция сохранит данные созданного процесса в child
    if (!start_program(argv[1], child)) //  Функция возвращает true, если запуск удался, или false, если произошла ошибка
    {
        cout << "Ошибка: не удалось запустить программу" << endl;
        return 1;
    }

    // Эта строка выполняется без ожидания завершения дочерней программы
    cout << "Родитель: Эта строка выполняется без ожидания завершения дочерней программы." << endl;

    // Функция ждёт завершения и записывает код дочерней программы в code
    int code;
    if (!wait_program(child, code))
    {
        cout << "Ошибка: не удалось получить код завершения дочерней программы" << endl;
        return 1;
    }

    cout << "Родитель: код завершения дочерней программы = " << code << endl;

    // Утилита выполнила проверку успешно. Это её собственный код завершения,
    // который отличается от полученного выше кода дочерней программы
    return 0;
}
