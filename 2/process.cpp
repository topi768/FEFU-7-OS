// spawn.h объявляет posix_spawn - функцию создания дочернего процесса
#include <spawn.h>
#include <cstddef> // Для NULL
#include <sys/wait.h> // waitpid и средства разбора результата ожидания
#include <cerrno> // errno и EINTR для проверки причины ошибки

// environ - предоставленный системой список переменных окружения нашей программы
// Например, в нём хранится PATH - список папок для поиска программ
// extern означает: переменная уже существует вне этого файла, здесь мы её объявляем
extern char** environ;

bool start_program(const char* path, Process& process)
{
    // Как и в Windows, проверяем, что передана непустая строка пути
    if (path == NULL || path[0] == '\0')
        return false;

    // Запускаемой программе нужен список аргументов - массив указателей на строки
    // Первый элемент принято отводить имени программы, последний должен быть NULL
    // Дополнительных аргументов в нашем интерфейсе пока нет
    // posix_spawn принимает char*, а path имеет тип const char*
    // const_cast приводит указатель к требуемому типу. Строку мы не меняем,
    // и posix_spawn также не должна изменять переданные строки аргументов
    char* args[] = {const_cast<char*>(path), NULL};

    // Создаём процесс без ожидания его завершения
    // При успехе система запишет PID по адресу &process
    int result = posix_spawn(
        &process, // Куда записать PID нового процесса
        path,     // Путь к запускаемому исполняемому файлу
        NULL,     // Дополнительные действия с файлами не задаём
        NULL,     // Используем обычные настройки создания процесса
        args,     // Список аргументов для дочерней программы
        environ   // Передаём ей переменные окружения нашей программы
    );

    // В отличие от CreateProcessA, posix_spawn возвращает 0 при успехе,
    // а ненулевое число при ошибке. Сравнение превращает этот результат в bool
    return result == 0;
}

bool wait_program(Process process, int& exit_code)
{
    // Положительное число обозначает конкретный PID
    // Ноль и отрицательные числа имеют у waitpid другое значение - нам они не нужны
    if (process <= 0)
        return false;

    // status будет содержать служебные данные о завершении процесса
    // Это ещё не сам код из return дочерней программы: его извлечём ниже
    int status;
    pid_t result;

    // do...while сначала выполняет тело, затем проверяет, нужно ли повторить его
    do
    {
        // Ждём дочерний процесс с указанным PID
        // &status - куда записать сведения о его завершении
        // 0 - обычное ожидание: если процесс работает, наш поток будет ждать
        // При успехе waitpid возвращает PID, при ошибке - -1
        result = waitpid(process, &status, 0);
    }
    // errno содержит причину ошибки последнего неудачного системного вызова
    // EINTR означает, что ожидание прервал сигнал - уведомление от ОС
    // В этом случае повторяем ожидание. При другой ошибке цикл заканчивается
    while (result == -1 && errno == EINTR);

    if (result == -1)
        return false;

    // WIFEXITED проверяет, завершилась ли программа обычным способом,
    // например через return из main. Если её завершил сигнал, обычного кода нет
    if (!WIFEXITED(status))
        return false;

    // WEXITSTATUS извлекает код завершения из служебного значения status
    // Записываем его в переменную вызывающего кода через ссылку exit_code
    exit_code = WEXITSTATUS(status);
    return true;
}

