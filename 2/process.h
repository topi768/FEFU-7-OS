// Файл .h (заголовок) описывает то, чем смогут пользоваться другие файлы программы
// Здесь задаём имя типа Process и объявляем две функции библиотеки
// Сам код этих функций будет находиться отдельно, в process.cpp

// PROCESS_H - просто имя. если оно еще неопредлено, то входим внутрь улсовия и внутри него опрделяем имя #define PROCESS_H. Это такая защита от повторной обработки заголовка при сборке
#ifndef PROCESS_H

#define PROCESS_H


#ifdef _WIN32 // если собираем программу для Windows, подключить заголовок для работы с Windows

#include <windows.h>

//  HANDLE это тип переменной, в которой хранится дескриптор - значение, выданное Windows для обращения к системному объекту. В нашем случае объект - процесс
typedef HANDLE Process; // Переименовываем HANDLE в Process


#else // случая, когда _WIN32 не определён, предполагается POSIX системы

#include <sys/types.h> // подключение системного заголовка, в котором объявлены различные типы POSIX. Среди них - pid_t

// PID - числовой идентификатор процесса, а pid_t - тип для хранения такого числа
// В POSIX мы будем ждать дочерний процесс по его PID
// Здесь даём типу pid_t то же общее имя Process
// Благодаря этому объявления функций ниже одинаковы для обеих ОС:
// в Windows Process означает HANDLE, а в POSIX - pid_t
typedef pid_t Process; // называем точно также как и в блоке с виндой 

// Конец выбора между Windows и POSIX, начатого строкой #ifdef _WIN32
#endif



// Её задача - запустить дочернюю программу и сразу вернуть управление нашей программе, не ожидая завершения дочерней
// bool - тип результата функции: true означает успешный запуск, false - ошибку запуска
// const char* path - параметр для передачи пути к запускаемой программе. const char* позволяет передать строку, например "C:\\Lab\\child.exe". Через этот параметр функция не должна изменять символы строки
// Process& process - параметр, в который функция запишет дескриптор или PID созданного процесса
// & чтобы функция могла изменить переменную, которую мы ей передали
// ПРИМЕР: Process child;
//         bool started = start_program("C:\\Lab\\child.exe", child);

// start_program(
//     "C:\\Lab\\child.exe", // Вход: какую программу запустить
//     child                // Выход: куда сохранить данные для обращения к процессу
// );
bool start_program(const char* path, Process& process);

// задача - дождаться завершения ранее запущенной программы и получить её код завершения
// Process process - передаём дескриптор или PID, полученный при запуске. Здесь нет &: передаётся копия этого значения. Сам дочерний процесс при этом не копируется
// int& exit_code - передаём по ссылке целочисленную переменную, в которую функция запишет код завершения дочерней программы
// bool - сообщает, удалось ли дождаться программы и получить её код
// wait_program будет приостанавливать вызвавший её поток до завершения дочернего процесса
// В Windows функция закрывает дескриптор: после вызова его нельзя использовать снова
// exit_code содержит полученный код только тогда, когда функция вернула true
// В POSIX завершение сигналом возвращает false: обычного кода завершения нет
// После успешного получения результата повторно ждать этот процесс не нужно
bool wait_program(Process process, int& exit_code);

// Конец защиты от повторного подключения, начатой строкой #ifndef PROCESS_H
#endif // PROCESS_H
