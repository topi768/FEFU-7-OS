#include <iostream>

// В C++98 нет общей стандартной функции для паузы
// Поэтому выбираем функцию операционной системы
#ifdef _WIN32
#include <windows.h> // Sleep: время задаётся в миллисекундах
#else
#include <unistd.h> // sleep: время задаётся в секундах
#endif

using namespace std;

int main()
{
#ifdef _WIN32
    // Настраиваем вывод русских строк в кодировке UTF-8 для консоли Windows
    SetConsoleOutputCP(CP_UTF8);
#endif

    cout << "Дочерняя программа: работа началась" << endl;

    // Приостанавливаем поток дочерней программы примерно на три секунды
    // Позже это позволит увидеть, что родитель продолжает работать после запуска,
    // а вызов wait_program ждёт завершения дочерней программы
#ifdef _WIN32
    Sleep(3000);
#else
    sleep(3);
#endif

    cout << "Дочерняя программа: работа завершена" << endl;

    // Заранее известный код завершения для проверки нашей библиотеки
    // Родительская программа должна получить именно 5 через wait_program
    return 5;
}
