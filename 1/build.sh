#!/bin/sh

# Остановить скрипт, если команда завершится с ошибкой
set -e

# Перейти в папку, в которой находится этот скрипт
# $0 содержит путь запуска скрипта
# dirname выделяет папку из этого пути
# Кавычки позволяют обрабатывать пути с пробелами
cd "$(dirname "$0")"

# Получить изменения из GitHub и обновить текущую ветку
# --ff-only запрещает автоматическое создание коммита слияния
# Если истории веток разошлись, скрипт остановится с ошибкой
echo "[1/3] Обновление исходников..."
git pull --ff-only

# Подготовить правила сборки по файлу CMakeLists.txt
# -S . указывает, что исходники находятся в текущей папке
# -B build-linux задаёт папку для файлов сборки
# Debug включает сборку с отладочной информацией для GDB
# Стандарт C++98 уже указан в CMakeLists.txt
echo "[2/3] Подготовка сборки..."
cmake -S . -B build-linux -DCMAKE_BUILD_TYPE=Debug

# Скомпилировать и скомпоновать программу
# CMake вызывает инструмент сборки, который запускает G++
# Готовая программа hello появится в папке build-linux
echo "[3/3] Сборка программы..."
cmake --build build-linux

# Это сообщение появится только после успешного выполнения всех шагов
echo "Сборка завершена успешно: build-linux/hello"
